let lastFactIndex = -1;

function showNextFact() {
    const factElement = document.getElementById('random-fact');
    if (!factElement || facts.length < 2) return; // Если фактов мало, проверка не нужна

    let randomIndex;

    // Генерируем новый индекс, пока он совпадает с предыдущим
    do {
        randomIndex = Math.floor(Math.random() * facts.length);
    } while (randomIndex === lastFactIndex);

    // Запоминаем текущий индекс для следующего раза
    lastFactIndex = randomIndex;

    // Плавная смена текста
    factElement.style.opacity = 0;
    setTimeout(() => {
        factElement.innerText = facts[randomIndex];
        factElement.style.opacity = 1;
    }, 300);
}

// Показываем первый факт сразу при загрузке
document.addEventListener('DOMContentLoaded', showNextFact);
